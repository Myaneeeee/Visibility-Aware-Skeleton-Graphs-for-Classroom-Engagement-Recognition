import os

import pytest

import download_videos as dv


# --- shortlist / url resolution ---------------------------------------------
# sav_dataset.txt carries only URLs, in sorted order of the source video ids.
# Line i therefore corresponds to the i-th id in sorted(clips_to_keep ids).

SORTED_IDS = ["20230101_08", "20230202_21", "20230303_34"]
URLS = ["https://v.youku.com/v_show/id_AAA==.html?playMode=pugv",
        "https://v.youku.com/v_show/id_BBB==.html?playMode=pugv",
        "https://v.youku.com/v_show/id_CCC==.html?playMode=pugv"]


def test_read_shortlist_takes_ids_and_skips_comments(tmp_path):
    p = tmp_path / "video_shortlist.txt"
    p.write_text("# generated by select_source_videos\n"
                 "# ranked by n_high\n"
                 "20230303_34\t10\t10\t0.439\n"
                 "20230101_08\t9\t10\t0.456\n")
    assert dv.read_shortlist(str(p)) == ["20230303_34", "20230101_08"]


def test_sorted_source_ids_dedupes_clips_and_sorts(tmp_path):
    p = tmp_path / "clips_to_keep.txt"
    p.write_text("20230303_34_5\n20230101_08_1\n20230303_34_6\n20230101_08_2\n")
    assert dv.sorted_source_ids(str(p)) == ["20230101_08", "20230303_34"]


def test_resolve_shortlist_urls_pairs_every_id_with_its_url():
    pairs = dv.resolve_shortlist_urls(["20230303_34", "20230101_08"], SORTED_IDS, URLS)
    assert pairs == [("20230101_08", URLS[0]), ("20230303_34", URLS[2])]


def test_resolve_shortlist_urls_rejects_an_unknown_id():
    with pytest.raises(ValueError, match="not in the source id list"):
        dv.resolve_shortlist_urls(["19990101_99"], SORTED_IDS, URLS)


def test_resolve_shortlist_urls_rejects_a_length_mismatch():
    # If the url list and the id list disagree, the positional mapping is void and
    # silently downloading the wrong videos would corrupt the whole join key.
    with pytest.raises(ValueError, match="length"):
        dv.resolve_shortlist_urls(["20230101_08"], SORTED_IDS, URLS[:2])


